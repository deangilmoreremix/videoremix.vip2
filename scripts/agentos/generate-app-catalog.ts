// Generates supabase/functions/_shared/app-catalog.ts from the browser app
// registry, so the agent runtime knows the same 117 Awesome LLM apps the
// dashboard shows. Run: npx tsx scripts/agentos/generate-app-catalog.ts
// tests/agentos/app-catalog.test.ts fails when the two drift apart.
import { writeFileSync } from "node:fs";
import { APP_REGISTRY } from "../../src/config/appRegistry";

const apps = APP_REGISTRY.filter((app) => app.family === "awesome-llm").map((app) => ({
  slug: app.slug,
  name: app.name,
  description: app.description.replace(/\s+/g, " ").trim().slice(0, 160),
  category: app.category,
}));

const body = `// GENERATED by scripts/agentos/generate-app-catalog.ts — do not edit by hand.
// The Awesome LLM apps an AgentOS agent can run through the videoremix_apps
// tool. Kept in sync with src/config/appRegistry.ts by
// tests/agentos/app-catalog.test.ts.

export interface CatalogApp {
  slug: string;
  name: string;
  description: string;
  category: string;
}

export const APP_CATALOG: CatalogApp[] = ${JSON.stringify(apps, null, 2)};

export const APP_CATALOG_BY_SLUG: Map<string, CatalogApp> = new Map(
  APP_CATALOG.map((app) => [app.slug, app]),
);
`;

writeFileSync("supabase/functions/_shared/app-catalog.ts", body);
console.log(`wrote ${apps.length} apps`);
